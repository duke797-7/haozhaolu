// 體驗版各頁截圖，用於檢查畫面。
import { createRequire } from 'node:module';
const require = createRequire('/opt/npm-tools/');
const { chromium, devices } = require('playwright');
const [,, wrap, out] = process.argv;
const b = await chromium.launch();
const c = await b.newContext({ ...devices['iPhone 14'], deviceScaleFactor: 1, locale: 'zh-TW', timezoneId: 'Asia/Taipei' });
const p = await c.newPage();
const shot = async (n, full = true) => { await p.waitForTimeout(150); await p.screenshot({ path: `${out}/${n}.png`, fullPage: full }); };
await p.goto(`file://${wrap}`);
await p.getByRole('heading', { name: '總覽' }).waitFor();
await shot('a-overview');
await p.getByRole('link', { name: '商品', exact: true }).click();
await p.getByTestId('product-row').first().waitFor();
await shot('b-products');
await p.getByRole('link', { name: '訂單', exact: true }).click();
await p.getByTestId('order').first().waitFor();
await shot('c-orders', false);
await p.getByRole('button', { name: '顧客頁' }).click();
await p.locator('.shop-card').first().waitFor();
await shot('d-home');
await p.locator('.shop-card').filter({ hasText: '棉麻' }).click();
await p.locator('.variant').first().waitFor();
await p.locator('.variant').nth(1).getByRole('button', { name: '增加一件' }).click();
await shot('e-product');
await p.getByRole('button', { name: '填寫預購單' }).click();
await p.getByLabel('取貨人姓名').fill('林小美');
await p.getByLabel('手機號碼', { exact: true }).fill('0912345678');
await p.getByRole('textbox', { name: /^Email/ }).fill('lin@example.com');
await p.getByRole('checkbox').check();
await shot('f-slip');
await p.getByRole('button', { name: '送出預購單' }).click();
await p.getByRole('heading', { name: '預購成功' }).waitFor();
await shot('g-thanks');
await b.close();
